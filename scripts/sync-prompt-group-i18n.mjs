/** Insert new entries right after ANCHOR_KEY, preserving the order of everything else. */
function withInsertedKeys(json, entries) {
  const out = {};
  const added = new Set(Object.keys(entries));
  for (const [key, value] of Object.entries(json)) {
    if (added.has(key)) continue; // re-inserted at the anchor below
    out[key] = value;
    if (key === ANCHOR_KEY) Object.assign(out, entries);
  }
  // Anchor missing (shouldn't happen): fall back to appending.
  for (const [key, value] of Object.entries(entries)) if (!(key in out)) out[key] = value;
  return out;
}

for (const dir of fs.readdirSync(localesRoot)) {
  const f = path.join(localesRoot, dir, 'messages.json');
  if (!fs.statSync(path.join(localesRoot, dir)).isDirectory() || !fs.existsSync(f)) continue;
  const j = JSON.parse(fs.readFileSync(f, 'utf8'));
  const t = T[dir] ?? T.en;
  const entries = {
    promptRequestCount: { message: t.count },
    promptRequestPager: { message: t.pager },
    promptPreviousRequest: { message: t.prev },
    promptNextRequest: { message: t.next },
    promptSkipRequest: { message: t.skip },
    promptIncludeRequest: { message: t.include },
    promptAppliesToGroup: { message: t.group },
    promptSkippedNote: { message: t.skippedNote },
  };
  fs.writeFileSync(f, JSON.stringify(withInsertedKeys(j, entries), null, 2) + '\n', 'utf8');
}

